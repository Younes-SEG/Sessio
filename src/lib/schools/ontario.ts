type Row = readonly [letter: string, min: number, points?: number];
const scale = (...rows: readonly Row[]) =>
  rows.map(([letter, min, points]) =>
    points === undefined ? { letter, min } : { letter, min, points },
  );
const source = (url: string, title: string) =>
  [{ url, title, checked: '2026-11-14' as const }] as const;

