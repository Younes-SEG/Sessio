import { z } from 'zod';
import type { AssessmentType } from './types';

export const gradingRuleSchema = z
  .object({
    id: z.string().min(1).max(200),
    name: z.string().trim().min(1).max(200),
    mode: z.enum(['best-of', 'equal']).optional(),
    assessmentType: z
      .enum(['ASSIGNMENT', 'LAB', 'QUIZ', 'MIDTERM', 'FINAL_EXAM', 'PROJECT', 'OTHER'])
      .optional(),
    keep: z.number().int().min(1).max(100),
    weight: z.number().finite().positive().max(100),
    assessmentIds: z.array(z.string().min(1).max(200)).max(100),
    source: z.string().max(2000),
  })
  .strict()
  .refine(
    (r) =>
      (r.mode === 'equal'
        ? Boolean(r.assessmentType)
        : r.assessmentIds.length >= 2 && r.keep < r.assessmentIds.length) &&
      new Set(r.assessmentIds).size === r.assessmentIds.length,
    'Choose distinct assessments and count fewer than the total.',
  );
export const gradingRulesSchema = z
  .array(gradingRuleSchema)
  .max(20)
  .refine((rules) => {
    const ids = rules.filter((r) => r.mode !== 'equal').flatMap((r) => r.assessmentIds);
    const types = rules.filter((r) => r.mode === 'equal').map((r) => r.assessmentType);
    return (
      new Set(types).size === types.length &&
      new Set(ids).size === ids.length &&
      new Set(rules.map((r) => r.id)).size === rules.length
    );
  }, 'An assessment can belong to only one grading rule.');
export type GradingRule = z.infer<typeof gradingRuleSchema>;
export const readGradingRules = (value: unknown): GradingRule[] => {
  const result = gradingRulesSchema.safeParse(value);
  return result.success ? result.data : [];
};
type WeightedItem = { id: string; weight: number; type?: AssessmentType };

/** Equal rules select every current member of a course category, including future imports. */
export function resolveGradingRules(rules: readonly GradingRule[], items: readonly WeightedItem[]) {
  return rules.map((r) => {
    if (r.mode !== 'equal') return r;
    const ids = items.filter((a) => a.type === r.assessmentType).map((a) => a.id);
    return { ...r, assessmentIds: ids, keep: Math.max(1, ids.length) };
  });
}

/** Derived weights leave original marks and manual weights intact in storage. */
export function withEqualWeights<T extends WeightedItem>(
  items: readonly T[],
  rules: readonly GradingRule[],
) {
  const weights = new Map<string, number>();
  for (const rule of resolveGradingRules(rules, items)) {
    if (rule.mode === 'equal')
      for (const id of rule.assessmentIds) weights.set(id, rule.weight / rule.assessmentIds.length);
  }
  return items.map((a) => (weights.has(a.id) ? { ...a, weight: weights.get(a.id)! } : a));
}

// Separate only the exact formats generated by the previous importer; preserve user prose.
export function splitGradingNotes(notes: string) {
  const lines = notes.split('\n');
  const generated = (line: string) =>
    /^.+: \d+(?:\.\d+)?% combined\. /.test(line) ||
    /^.+: user confirmed equal allocation of the remaining category weight across \d+ assessments with missing weights\.$/.test(
      line,
    );
  return {
    instructions: lines.filter((l) => !generated(l)).join('\n'),
    references: lines.filter(generated).join('\n'),
  };
}

export function configuredCourseWeight(
  items: readonly WeightedItem[],
  rules: readonly GradingRule[] = [],
) {
  const grouped = new Set(resolveGradingRules(rules, items).flatMap((r) => r.assessmentIds));
  return (
    items.reduce((n, a) => n + (grouped.has(a.id) ? 0 : a.weight), 0) +
    rules.reduce((n, r) => n + r.weight, 0)
  );
}
export function gradingRuleError(rules: readonly GradingRule[], items: readonly WeightedItem[]) {
  const parsed = gradingRulesSchema.safeParse(rules);
  if (!parsed.success)
    return 'Check the grading rules: counts, weights and assessment selections must be valid.';
  const ids = new Set(items.map((a) => a.id));
  const resolved = resolveGradingRules(rules, items);
  const groupedIds = resolved.flatMap((r) => r.assessmentIds);
  if (new Set(groupedIds).size !== groupedIds.length)
    return 'An assessment can belong to only one grading rule.';
  if (resolved.some((r) => r.assessmentIds.some((id) => !ids.has(id))))
    return 'A grading rule includes a missing assessment. Update its selection before saving.';
  if (configuredCourseWeight(items, rules) > 100.000001)
    return 'Course weights, including grading groups, cannot exceed 100%.';
  return null;
}

// Deliberately narrow interpretation: unsupported instructions remain notes, never silent formulas.
export function interpretGradingNote(
  note: string,
): { keep: number; count: number; type: AssessmentType; weight: number | null } | null {
  const text = note
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase();
  if (/\b(not|never|except|unless|pas|jamais|sauf)\b/.test(text)) return null;
  const matches = [
    ...text.matchAll(
      /(?:best|highest|top)\s+(\d+)\s*(?:out\s+of|of|\/)\s*(\d+)|(?:les\s+)?(\d+)\s+meilleur\w*\s+(?:[\w'-]+\s+){0,4}?(?:sur|de)\s+(\d+)/g,
    ),
  ];
  if (matches.length !== 1) return null;
  const keep = Number(matches[0][1] || matches[0][3]);
  const count = Number(matches[0][2] || matches[0][4]);
  const types: AssessmentType[] = [];
  if (/\b(quiz\w*|questionnaire\w*)\b/.test(text)) types.push('QUIZ');
  if (/\b(lab\w*|laboratoire\w*)\b/.test(text)) types.push('LAB');
  if (/\b(assignment\w*|devoir\w*)\b/.test(text)) types.push('ASSIGNMENT');
  if (types.length !== 1 || keep < 1 || count > 100 || keep >= count) return null;
  // Weight must be confirmed separately; a percentage could refer to a single assessment.
  return { keep, count, type: types[0], weight: null };
}
